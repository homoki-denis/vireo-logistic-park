const docks = (code: string, face: Face, ats: number[], w = 4.2): DoorSpec[] =>
  ats.map((at, i) => ({ face, at, w, h: 4.4, dock: true, name: `Rampa ${code}-${i + 1}` }));

const accent = (code: string) => DEPOT_BY_CODE.get(code)!.accent;

const info = (code: string, desc: string) => {
  const d = DEPOT_BY_CODE.get(code)!;
  return { type: d.category, desc, capacity: d.capacity || undefined };
};

