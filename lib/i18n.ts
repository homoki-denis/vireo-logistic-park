/** pattern translations for generated strings */
const PATTERNS: [RegExp, string][] = [
  [/^Șef depozit (\w+)$/, "$1 warehouse manager"],
  [/^Rampa (.+)$/, "Dock $1"],
  [/^Poartă (.+)$/, "Gate $1"],
  [/^Încarcă la (.+)$/, "Loading at $1"],
  [/^Descarcă la (.+)$/, "Unloading at $1"],
  [/^Preia colete de la (.+)$/, "Picking up parcels at $1"],
  [/^(\d+) locuri$/, "$1 spots"],
  [/^Culoar (\w+) · Raft (\d+) · Nivel (\d+)$/, "Aisle $1 · Rack $2 · Level $3"],
];

export function translateData(s: string, lang: Lang): string {
  if (lang === "ro" || !s) return s;
  const hit = DATA_EN[s];
  if (hit) return hit;
  for (const [re, rep] of PATTERNS) if (re.test(s)) return s.replace(re, rep);
  return s;
}

export function translateUi(lang: Lang, key: UiKey, vars?: Record<string, string | number>) {
  let s: string = UI[lang][key] ?? UI.ro[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** React hook: const { t, d, lang, nf } = useT() */
export function useT() {
  const lang = useStore((s) => s.lang);
  return {
    lang,
    t: (key: UiKey, vars?: Record<string, string | number>) => translateUi(lang, key, vars),
    d: (s: string) => translateData(s, lang),
    nf: (n: number) => n.toLocaleString(lang === "ro" ? "ro-RO" : "en-GB"),
    locale: lang === "ro" ? "ro-RO" : "en-GB",
  };
}
